def splat_f32_bits(attribute):
 """Decode an MLIR dense f32 splat without losing hexadecimal payload bits."""
 if not isinstance(attribute,str) or not attribute.lstrip().startswith('dense<') or '>' not in attribute.split('dense<',1)[1]:
  raise ValueError('f32 constant must be a dense scalar splat')
 token=attribute.split('dense<',1)[1].split('>',1)[0].strip()
 if re.fullmatch(r'0[xX][0-9a-fA-F]{8}',token):return int(token,16)
 if not re.fullmatch(r'[+-]?(?:(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?|inf|nan)',token,re.IGNORECASE):
  raise ValueError('f32 constant must be a dense scalar splat; unsupported literal')
 try:return struct.unpack('<I',struct.pack('<f',float(token)))[0]
 except (ValueError,OverflowError) as error:raise ValueError('f32 splat literal is out of range') from error

