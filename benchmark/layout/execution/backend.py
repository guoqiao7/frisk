 def _emit_shuffle_network(self,network,source):
  """Emit the independently verified pullback network as bitwise PTX.

  Every shuffle is unconditional and convergent. Logical register permutations
  are aliases; no floating-point operation touches transported payload bits.
  The counts are checked against actual emitted grammar, not a latency guess.
  """
  registers=list(source);start=len(self.code);declarations=len(self.decl);predicates={};communication_stages=0
  def predicate(mask,constant):
   key=(mask,constant)
   if key not in predicates:
    if not mask:raise ValueError('constant network predicate was not canonicalized')
    value=self.tmp();self.emit(f'and.b32 {value}, tid, {mask};')
    if mask&(mask-1):
     self.emit(f'popc.b32 {value}, {value};');self.emit(f'and.b32 {value}, {value}, 1;')
    pred=self.tmp('pred');op='eq' if constant else 'ne';self.emit(f'setp.{op}.u32 {pred}, {value}, 0;');predicates[key]=pred
   return predicates[key]
