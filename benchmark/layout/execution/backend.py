 def _copy_vector16(self, source, target, execution, contract, *, publish):
  shape = execution['shape']
  expected = dict(version=1, path='vector', target='sm_90a', vector_bytes=16,
                  valid_shape=shape, guarded=0, issuer='execution-map', completion='synchronous')
  nr = execution['topology'][0]
  src_root, dst_root = (self.storage(v)['root'] for v in (source, target))
  slots = execution['logical']
  if (contract != expected or nr % 8 or nr * 128 != math.prod(shape)
      or src_root not in self.roots or dst_root not in self.smem):
   raise ValueError('unsupported aligned synchronous Copy contract')
  if any(self.storage(root)['alignment'] < 16 for root in (src_root, dst_root)) or self.smem[dst_root] % 16:
   raise ValueError('aligned Copy roots require 16-byte alignment')
  if sorted(slots) != list(range(len(slots))) or any(execution['first'][slot] != i for i, slot in enumerate(slots)):
   raise ValueError('aligned Copy requires unique first owners')
  offsets = [self.offsets(value) for value in (source, target)]
  tables = [[], []]
  for r in range(0, nr, 8):
   groups = [slots[t * nr + r:t * nr + r + 8] for t in range(128)]
   for endpoint, offset in enumerate(offsets):
    starts = [offset[group[0]] for group in groups]
    if any(offset[slot] != base + 2 * i for group, base in zip(groups, starts) for i, slot in enumerate(group)):
     raise ValueError('aligned Copy elements are not contiguous')
    tables[endpoint].append(starts)

  owner_receipt = {}
  if self.copy_owner_policy == 'gf2' and self.access_policy == 'vector':
   plan = plan_copy_owners(*tables)
   if plan is not None:
    tables, receipt = plan
    owner_receipt['copy_owners'] = receipt

  all_threads = (1 << 128) - 1
  proof_src = plan_access(tables[0], element_bytes=16, root_alignment=self.storage(src_root)['alignment'],
                         root_bytes=self._root_bytes(src_root))
  proof_dst = plan_access(tables[1], element_bytes=16, root_alignment=self.storage(dst_root)['alignment'],
                         root_bytes=self._root_bytes(dst_root), owner_masks=[all_threads] * len(tables[1]))
  src_bases, dst_bases = {}, {}
  dst_groups = {group.slots[0]: group for group in proof_dst.groups}

  def address_for(group, table, proof, bases, materialize):
   if group.width_bytes != 16 or len(group.slots) != 1:
    raise ValueError('aligned Copy cannot honor its 16-byte contract')
   if self.access_policy == 'legacy':
    return materialize(self.map(table[group.slots[0]])), 0
   if group.base_index not in bases:
    bases[group.base_index] = materialize(self.map(proof.bases[group.base_index]))
   return bases[group.base_index], group.byte_offset

  for group in proof_src.groups:
   src, src_delta = address_for(group, tables[0], proof_src, src_bases,
                                lambda offset: self.address(src_root, offset))
   dst, dst_delta = address_for(dst_groups[group.slots[0]], tables[1], proof_dst, dst_bases,
                                lambda offset: self.shared(target, offset))
   vector = '{' + ', '.join(self.tmp() for _ in range(4)) + '}'
   self.emit(f'ld.global.v4.b32 {vector}, [{src}+{src_delta}];')
   self.emit(f'st.shared.v4.b32 [{dst}+{dst_delta}], {vector};')
  if publish:
   self.emit('bar.sync 0;')
   self.emit('fence.proxy.async.shared::cta;')
  self._record_access('copy',2,{16:len(proof_src.groups)},
                      len(proof_src.groups) if self.access_policy == 'legacy' else len(src_bases),
                      proof_src,16,self.storage(src_root)['alignment'],**owner_receipt)

