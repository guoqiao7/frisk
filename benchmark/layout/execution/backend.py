 def _check_sliced_mma(self, operation, contract):
  """Recheck the exported bounded SM90 descriptor proof before extending geometry."""
  attrs = operation['attrs']
  m, n, k = (attrs.get(dim) for dim in ('m', 'n', 'k'))
  form = contract['form']
  supported = ((64,64,32), (64,64,64), (64,128,16), (64,128,32), (64,256,16), (64,256,32)) if form == 'ss' else (
      (64,32,64), (64,32,128), (64,32,256))
  if ((m,n,k) not in supported or attrs.get('trans_a') != 0 or attrs.get('trans_b') != (-1 if form == 'ss' else 0)
      or contract['atom'] != [64,n,16] or contract['repeats'] != [1,1,k//16]):
   raise ValueError('unsupported sliced MMA geometry')

  a, b = operation['operands'][:2]
  operands = ((a, 'a_descriptor', m, True), (b, 'b_descriptor', n, True)) if form == 'ss' else (
      (b, 'b_descriptor', n, False),)
  for operand, key, mn_extent, k_second in operands:
   storage = self.storage(operand)
   root = storage['root']
   desc = contract[key]
   if root not in self.smem or set(desc) != {'entries','leading','major','stride','swizzle'}:
    raise ValueError('sliced MMA requires Shared storage and a complete descriptor')
   major, swizzle, leading, stride = (desc[x] for x in ('major','swizzle','leading','stride'))
   if (major != ('k' if k_second else 'mn') or swizzle not in (0,32,64,128)
       or any(type(x) is not int or x < 0 or x % 16 or x >= 1 << 18 for x in (leading,stride))
       or (major=='k' and swizzle and leading != 16)):
    raise ValueError('invalid sliced MMA descriptor fields')
   alignment = max(16,swizzle*8)
   if self.storage(root)['alignment'] < alignment or self.smem[root] % alignment:
    raise ValueError('sliced MMA root alignment')
   self._storage_element_width(operand, 2)
   actual = self.offsets(operand)
   root_bytes = self._root_bytes(root)
   entries = desc['entries']
   if len(entries) != k//4 or any(type(x) is not int for x in entries):
    raise ValueError('sliced MMA descriptor entry count')
   scale = max(1,swizzle//16)
   mask = scale-1
   # Same root-relative SM90 address relation as SM90MmaLayoutProof.cpp.
   for k_start in range(0,k,16):
    mn, column, start, phase = entries[k_start//4:k_start//4+4]
    if (mn != 0 or column != k_start or start < 0 or start % 16
        or self.smem[root]+start >= 1 << 18 or phase != ((start >> 7) & 7 if swizzle else 0)):
     raise ValueError('sliced MMA descriptor start or phase')
    for i in range(mn_extent):
     for j in range(16):
      if major=='k':
       relative = i%8*(16*scale) + i//8*stride + j%8*2 + j//8*(16 if swizzle else leading)
      elif not swizzle:
       relative = i%8*2 + i//8*stride + j%8*16 + j//8*leading
      else:
       relative = i%(8*scale)*2 + i//(8*scale)*leading + j%8*(16*scale) + j//8*stride
      unswizzled = (start ^ ((phase & mask)<<4)) + relative
      expected = unswizzled ^ (((unswizzled>>7)&mask)<<4)
      index = i*k + k_start+j if k_second else (k_start+j)*mn_extent+i
      if actual.get(index) != expected or expected+2 > root_bytes:
       raise ValueError('sliced MMA descriptor disagrees with checked root address')

 def reduce(self,o):
  from reduction_plan import plan_ordered_warp_reduction, verified_warp_reduction_trees

  src, = o['operands']
  dst, = o['results']
  if any('xf32' not in self.v[v]['type'].split(',')[0] or
         self.v[v]['distributed']['topology'][1:] != [32,4,1,1] for v in (src,dst)):
   raise ValueError('checked reduction requires f32 tensors and 128 execution threads')
  proof = verified_warp_reduction_trees(o, self.v[src]['distributed'], self.v[dst]['distributed'])
  plan = plan_ordered_warp_reduction(proof) if self.reduction_policy == 'auto' else None
  if plan is None:
   trees = proof.eager_registers()
   if trees is None:
    raise ValueError('unsupported reduction communication')
  values = self.regs(src)
  operation = {'sum':'add.rn.f32','max':'max.f32'}[o['attrs']['kind'].strip('"')]
  outputs = self.newregs(dst)
  predicates = {}

  def combine(left,right):
   result = self.tmp('f32')
   self.emit(f'{operation} {result}, {left}, {right};')
   return result

  def tree_value(tree):
   if tree[0] == 'combine':
    return combine(tree_value(tree[1]), tree_value(tree[2]))
   source = values[tree[1]]
   if len(tree) == 2:
    return source
   table = tree[2]
   base = table[0]
   mask = table[-1] ^ base
   if not mask:
    index = base
   elif all(lane == ((i & mask) | base) for i,lane in enumerate(table)):
    index = self.tmp()
    self.emit(f'and.b32 {index}, lane, {mask};')
    self.emit(f'or.b32 {index}, {index}, {base};')
   else:
    index = self.map(table)
   received = self.tmp()
   self.emit(f'shfl.sync.idx.b32 {received}, {source}, {index}, 31, -1;')
   return received

  def left_predicate(stage):
   key = stage.parity_mask, stage.left_parity
   if key not in predicates:
    mask, parity = key
    value = self.tmp()
    pred = self.tmp('pred')
    self.emit(f'and.b32 {value}, lane, {mask};')
    if mask & (mask-1):
     self.emit(f'popc.b32 {value}, {value};')
     self.emit(f'and.b32 {value}, {value}, 1;')
     mask = 1
    self.emit(f'setp.eq.u32 {pred}, {value}, {mask if parity else 0};')
    predicates[key] = pred
   return predicates[key]

  if plan is None:
   for output, tree in zip(outputs, trees):
    self.emit(f'mov.b32 {output}, {tree_value(tree)};')
  else:
   for output, register in zip(outputs, plan.registers):
    value = tree_value(register.local_tree)
    for stage in register.stages:
     other = self.tmp()
     self.emit(f'shfl.sync.bfly.b32 {other}, {value}, {stage.xor_mask}, 31, -1;')
     pred = left_predicate(stage)
     left, right = self.tmp(), self.tmp()
     self.emit(f'selp.b32 {left}, {value}, {other}, {pred};')
     self.emit(f'selp.b32 {right}, {other}, {value}, {pred};')
     value = combine(left,right)
    self.emit(f'mov.b32 {output}, {value};')
  self.reduction_plans.append(dict(scope=proof.scope, strategy='ordered-butterfly' if plan else 'ordered-eager',
                                  butterfly_masks=[[s.xor_mask for s in r.stages] for r in plan.registers] if plan else []))

